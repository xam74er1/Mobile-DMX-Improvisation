"""
Shared packet-logging helper for the DMX debug toolkit.

Records every packet this toolkit sends or receives, with enough detail
to reconstruct exactly what went out (or came back): timestamp, protocol,
direction, host:port, raw bytes as hex, and a short summary. Mirrors the
app's own in-app debug log (src/dmx/debugLog.ts) so a report generated by
this script and one exported from the phone/tablet app can be compared
side by side using the same vocabulary.

Two exports are written at the end of a session:
  - a JSON-Lines file (one JSON object per packet) for programmatic
    analysis later, e.g. `jq`, pandas, a notebook, a diff against a
    previous session's export.
  - a plain-text hex-dump twin, readable without any tooling at all.

This is *not* a substitute for a real packet capture. If you need to see
what's actually happening below the application layer (retransmits, ICMP
errors, ARP, TCP handshakes), use Wireshark: https://www.wireshark.org/ —
this log only records what this script itself sent/received at the
socket API level.
"""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Literal, Optional

Direction = Literal["tx", "rx"]


@dataclass
class PacketEntry:
    time: float
    protocol: str          # "artnet" | "freedmx" | "ws" | "http"
    direction: Direction   # "tx" = this tool sent it, "rx" = it received something back
    host: str
    port: int
    byte_length: int
    hex: str
    summary: str
    ok: bool = True
    error: Optional[str] = None


class PacketLog:
    def __init__(self) -> None:
        self.entries: list[PacketEntry] = []

    def log(
        self,
        protocol: str,
        direction: Direction,
        host: str,
        port: int,
        data: bytes,
        summary: str = "",
        ok: bool = True,
        error: Optional[str] = None,
    ) -> None:
        self.entries.append(
            PacketEntry(
                time=time.time(),
                protocol=protocol,
                direction=direction,
                host=str(host),
                port=port,
                byte_length=len(data),
                hex=hex_dump(data),
                summary=summary or summarize_channels(data),
                ok=ok,
                error=error,
            )
        )

    def export_jsonl(self, path: Path) -> None:
        with path.open("w", encoding="utf-8") as f:
            for e in self.entries:
                f.write(json.dumps(asdict(e)) + "\n")

    def export_text(self, path: Path) -> None:
        with path.open("w", encoding="utf-8") as f:
            for e in self.entries:
                ts = time.strftime("%Y-%m-%dT%H:%M:%S", time.localtime(e.time))
                status = "OK" if e.ok else "FAIL"
                arrow = "->" if e.direction == "tx" else "<-"
                f.write(
                    f"[{ts}] {status} {e.protocol.upper()} {arrow} {e.host}:{e.port} "
                    f"({e.byte_length}B)\n"
                )
                if e.error:
                    f.write(f"  error: {e.error}\n")
                f.write(f"  {e.summary}\n")
                f.write(f"  {e.hex}\n\n")


def hex_dump(data: bytes, width: int = 16) -> str:
    """Space-separated uppercase hex, wrapped like a classic hex dump —
    the same formatting convention as the app's own debugLog.ts hexDump()."""
    lines = []
    for i in range(0, len(data), width):
        chunk = data[i : i + width]
        hex_part = " ".join(f"{b:02X}" for b in chunk)
        lines.append(f"{i:04x}  {hex_part}")
    return "\n".join(lines)


def summarize_channels(data: bytes) -> str:
    """Best-effort non-zero-byte summary for a raw buffer — meaningful for
    buffers that are literally a flat list of DMX values (an Art-Net
    payload, or a freeDMX-native chunk); callers pass their own summary
    for anything else (JSON bodies, handshake bytes, etc.)."""
    if not data:
        return "(empty)"
    nonzero = [f"{i + 1}:{b}" for i, b in enumerate(data) if b]
    if not nonzero:
        return "all zero"
    if len(nonzero) > 12:
        return ", ".join(nonzero[:12]) + f", +{len(nonzero) - 12} more"
    return ", ".join(nonzero)
